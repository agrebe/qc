"""Emit qc_config.h: the compile-time facts an installed libqc was built for.

The geometry is part of qc's ABI -- lattice extents, the rank grid, num_rhs
and the arithmetic precision are #defines baked into loop bounds and into
generated assembly, so an archive sitting in /usr/local/lib is valid for
exactly one configuration and nothing about the file says which.  This header
is what makes it self-describing: installed alongside qc.h, it lets a consumer
check at compile time what qc.h's qc_global_dims / qc_num_rhs /
qc_native_precision would only tell them at run time.

Values come from the C preprocessor via hdr_params.hdr_int, the same path the
asm generators use, so this header cannot disagree with what the library
compiled against and no generator needs to know which header holds a given
parameter.  The two facts cpp cannot supply -- the size of REAL, which needs
sizeof, and whether MPI is on, which is a make-level choice -- are passed in
by the Makefile.

Nothing here is trusted on faith: test/collide.c includes qc_config.h, links
the built library, and asserts every macro against the corresponding runtime
query.

Usage (from the repo root, as the Makefile runs it):
    python3 gen_qc_config.py <precision-bytes> <mpi 0|1> <output path>
"""
import os, sys

# hdr_params lives in avx/ because the kernel generators needed it first; it
# is not specific to them.  A script's own directory is on sys.path, not its
# subdirectories, so point at avx/ explicitly rather than relying on the
# working directory.
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "avx"))
from hdr_params import hdr_int

if len(sys.argv) != 4:
    sys.exit(__doc__.strip().splitlines()[-1])
precision_bytes, mpi, out_path = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]

if precision_bytes not in (4, 8):
    sys.exit(f"gen_qc_config: precision must be 4 or 8 bytes, got {precision_bytes}")

# (macro in this header, macro in the C headers).  Lz/Lt are read in their
# _glob form: the local extents are a function of the rank grid, and what a
# consumer needs to know is the whole lattice.
GEOMETRY = [
    ("QC_CONFIG_LX",          "Lx"),
    ("QC_CONFIG_LY",          "Ly"),
    ("QC_CONFIG_LZ",          "Lz_glob"),
    ("QC_CONFIG_LT",          "Lt_glob"),
    ("QC_CONFIG_NUM_RHS",     "num_rhs"),
    ("QC_CONFIG_NC",          "Nc"),
    ("QC_CONFIG_NS",          "Ns"),
    ("QC_CONFIG_MPI_GRID_PZ", "MPI_GRID_PZ"),
    ("QC_CONFIG_MPI_GRID_PT", "MPI_GRID_PT"),
]

values = [(name, hdr_int(macro)) for name, macro in GEOMETRY]
width = max(len(name) for name, _ in values) + 1

lines = [
    "// Copyright 2026, University of Maryland, All Rights Reserved",
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "//",
    "// Generated by gen_qc_config.py -- do not edit.",
    "//",
    "// What this copy of libqc was built for.  These are compile-time constants, so a",
    "// consumer can check them with #if and fail to build rather than discovering a",
    "// mismatch at run time; qc.h's qc_global_dims(), qc_num_rhs() and",
    "// qc_native_precision() report the same values while running.",
    "//",
    "// A build is valid for exactly one of these configurations.  Passing fields sized",
    "// for a different lattice, a different num_rhs or a different precision is not",
    "// diagnosed by the library -- solver fields are void * -- so checking here is the",
    "// only thing standing between a mismatch and silent corruption.",
    "",
    "#ifndef QC_CONFIG_H",
    "#define QC_CONFIG_H",
    "",
]
lines += [f"#define {name:<{width}} {value}" for name, value in values]
lines += [
    "",
    "// Bytes per real in a solver field: 8 for the mixed and double builds (whose outer",
    "// solver and public fields are fp64), 4 for the uniform single build.  Numerically",
    "// equal to the qc_precision enum qc_native_precision() returns.",
    f"#define QC_CONFIG_PRECISION {precision_bytes}",
    "",
    "// 1 if this build links MPI, in which case qc_mpi.h is installed alongside this",
    "// header and qc_set_comm exists.  At 0 there is no MPI dependency at all.",
    f"#define QC_CONFIG_MPI {mpi}",
    "",
    "#endif",
    "",
]

with open(out_path, "w") as f:
    f.write("\n".join(lines))

dims = "x".join(str(v) for n, v in values[:4])
print(f"wrote {out_path} for {dims}, num_rhs={dict(values)['QC_CONFIG_NUM_RHS']}, "
      f"{precision_bytes}-byte reals, grid "
      f"{dict(values)['QC_CONFIG_MPI_GRID_PZ']}x{dict(values)['QC_CONFIG_MPI_GRID_PT']}, "
      f"MPI={mpi}")
